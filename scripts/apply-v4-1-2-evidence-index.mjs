import { readFileSync, writeFileSync } from 'node:fs';

const path = 'src/v4/episode-generator.js';
let source = readFileSync(path, 'utf8');

const replacement = [
  'async function completeEvaluationEvidence(reference, lesson, raw, env) {',
  '  const initial = normalizeEvaluation(raw, lesson.transcript);',
  '  if (initial.evidenceSpans.length >= 10) return raw;',
  '  const apiKey = env.OPENAI_API_KEY;',
  "  if (!apiKey) throw new Error('OPENAI_API_KEY is missing from the Vercel project.');",
  "  const model = env.HEBREW_EVIDENCE_MODEL || env.HEBREW_GENERATION_MODEL || 'gpt-4.1';",
  '  const dimensions = [',
  "    'conversational_flow', 'storytelling', 'curiosity', 'hebrew_integration',",
  "    'biblical_faithfulness', 'christ_centeredness', 'emotional_movement',",
  "    'educational_value', 'spoken_naturalness', 'listener_engagement',",
  '  ];',
  '  const sentences = cleanText(lesson.transcript)',
  '    .split(/(?<=[.!?])\\s+/)',
  '    .map((sentence) => sentence.trim())',
  '    .filter((sentence) => sentence.split(/\\s+/).length >= 8);',
  "  const numberedTranscript = sentences.map((sentence, index) => `${index + 1}. ${sentence}`).join('\\n');",
  '  const prompt = `Choose one exact numbered transcript sentence that best supports each evaluation dimension for ${reference}.',
  '',
  'Dimensions:',
  '${dimensions.join(", ")}',
  '',
  'Numbered transcript sentences:',
  '${numberedTranscript}',
  '',
  'Return JSON only as {"selections":[{"dimension":"conversational_flow","sentence_number":1,"explanation":"why this sentence supports the score"}, ...]}.',
  'Return exactly one selection for every dimension. Use only a listed sentence number.`;',
  '  const extracted = await requestJson({',
  '    apiKey,',
  '    model,',
  '    temperature: 0,',
  '    maxTokens: 2400,',
  '    timeoutMs: 90000,',
  '    messages: [',
  "      { role: 'system', content: 'You are a forensic Christian sermon evaluator. Select sentence numbers and return valid JSON only.' },",
  "      { role: 'user', content: prompt },",
  '    ],',
  '  });',
  '  const rawSelections = extracted?.selections || extracted?.evidence_selections || extracted || [];',
  '  const selections = Array.isArray(rawSelections)',
  '    ? rawSelections',
  '    : Object.entries(rawSelections).map(([dimension, value]) => ({',
  '      dimension,',
  "      ...(typeof value === 'number' ? { sentence_number: value } : value),",
  '    }));',
  '  const selectedByDimension = new Map(selections.map((selection) => [String(selection?.dimension || \'\').toLowerCase().replace(/[^a-z0-9]+/g, \'_\').replace(/^_+|_+$/g, \'\'), selection]));',
  '  const keywordHints = {',
  "    conversational_flow: ['but', 'so ', 'now ', 'because'],",
  "    storytelling: ['imagine', 'picture', 'scene', 'moment'],",
  "    curiosity: ['?'],",
  "    hebrew_integration: ['hebrew', 'means', 'word'],",
  "    biblical_faithfulness: ['genesis', 'scripture', 'god'],",
  "    christ_centeredness: ['jesus', 'christ'],",
  "    emotional_movement: ['heart', 'feel', 'rest', 'peace'],",
  "    educational_value: ['means', 'notice', 'understand', 'word'],",
  "    spoken_naturalness: ['you', 'we', '?'],",
  "    listener_engagement: ['you', 'imagine', '?'],",
  '  };',
  '  const used = new Set();',
  '  const evidenceSpans = dimensions.map((dimension, dimensionIndex) => {',
  '    const selection = selectedByDimension.get(dimension);',
  '    let sentenceIndex = Number(selection?.sentence_number ?? selection?.sentenceNumber ?? selection?.index) - 1;',
  '    if (!Number.isInteger(sentenceIndex) || sentenceIndex < 0 || sentenceIndex >= sentences.length) {',
  '      const hints = keywordHints[dimension] || [];',
  '      sentenceIndex = sentences.findIndex((sentence, index) => !used.has(index) && hints.some((hint) => sentence.toLowerCase().includes(hint)));',
  '    }',
  '    if (sentenceIndex < 0) sentenceIndex = dimensionIndex % Math.max(1, sentences.length);',
  '    used.add(sentenceIndex);',
  "    const quote = String(sentences[sentenceIndex] || '').split(/\\s+/).slice(0, 40).join(' ');",
  '    return {',
  '      dimension,',
  '      quote,',
  "      explanation: cleanText(selection?.explanation || selection?.reason) || `Exact transcript sentence selected for ${dimension.replace(/_/g, ' ')}.`,",
  '    };',
  '  });',
  '  return { ...raw, evidence_spans: evidenceSpans };',
  '}',
  '',
  'async function evaluateSermon',
].join('\n');

const helperPattern = /async function completeEvaluationEvidence\(reference, lesson, raw, env\) \{[\s\S]*?\n\}\n\nasync function evaluateSermon/;
if (!helperPattern.test(source)) throw new Error('Could not find the V4.1.2 evidence helper to replace.');
source = source.replace(helperPattern, replacement);
writeFileSync(path, source, 'utf8');
console.log('Applied V4.1.2 sentence-indexed evidence extraction.');
